class AppToast extends HTMLElement {
    connectedCallback() {

        this.offsetHeight;

        requestAnimationFrame(() => {
            this.classList.add("show");
        })

        setTimeout(() => {
            this.classList.remove('show');
        }, 3000);

        this.addEventListener("transitionend", () => {
            if(!this.classList.contains('show')) {
                this.remove();
            }
        });
    }
}
